package Exercicios_While;
public class Exercicio5 {
    public static void main(String[] args) {
        int i = 1;

        while (i <= 10) {
            int tabuada = i * 5;
            System.out.println("A tabuada de " + i + " vezes 5 é " + tabuada);
            i++;
        }
    }
}
